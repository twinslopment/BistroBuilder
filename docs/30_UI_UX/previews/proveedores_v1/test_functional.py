import asyncio,json
from pathlib import Path
from playwright.async_api import async_playwright
root=Path('/mnt/data/proveedores_bloque04')
html=(root/'BistroBuilder_Proveedores_Bloque04_Preview_V1.html').read_text(encoding='utf8')
async def main():
    log=[]; errors=[]
    async with async_playwright() as p:
        b=await p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
        page=await b.new_page(viewport={'width':1920,'height':1080})
        page.on('pageerror',lambda e:errors.append(str(e)))
        await page.set_content(html,wait_until='load')
        async def step(name,condition):
            assert condition,name;log.append('PASS '+name)
        await step('Proveedor / 6 filas',await page.locator('.table-row').count()==6)
        await page.locator('button[data-filter="Bloqueados"]').click()
        await step('Filtro bloqueados',await page.locator('.table-row').count()==1)
        await page.locator('.table-row').first.click();await page.wait_for_timeout(165)
        await step('Ficha proveedor bloqueado',await page.locator('#drawer').get_attribute('aria-hidden')=='false' and 'Bloqueado' in (await page.locator('#drawerHead').inner_text()))
        await page.locator('button[data-tab="catalog"]').click()
        await step('Catálogo 14 ofertas',await page.locator('.table-row').count()==14)
        await page.locator('button[data-filter="Promociones"]').click()
        await step('Filtro promociones',await page.locator('.table-row').count()==3)
        await page.locator('button[data-filter="Todos"]').click()
        await page.locator('#searchInput').fill('merluza')
        await step('Búsqueda por ingrediente',await page.locator('.table-row').count()==1)
        await page.locator('.table-row').first.click();await page.wait_for_timeout(165)
        await step('Detalle catálogo', 'Merluza fresca' in await page.locator('#drawerHead').inner_text())
        await page.locator('[data-action="incQty"]').click()
        await step('Sumar envase',await page.locator('#packQty').input_value()=='2')
        await page.locator('[data-action="addDraft"]').click()
        await step('Crear pedido borrador', 'Pedidos del restaurante' in await page.locator('#screenTitle').inner_text() and 'P-2042' in await page.locator('#drawerHead').inner_text())
        await page.locator('[data-action="confirmOrder"]').click()
        await step('Abre confirmación explícita',await page.locator('#orderDialog').evaluate('(el)=>el.open'))
        await page.locator('#submitOrder').click()
        await step('Confirma pedido', 'Confirmado' in await page.locator('#drawerHead').inner_text())
        await page.locator('#resetDemo').click()
        await step('Reset borradores y vuelta inicial',await page.locator('.table-row').count()==6 and 'Proveedores' in await page.locator('#screenTitle').inner_text())
        await page.locator('button[data-tab="smart"]').click()
        await page.locator('button[data-row="equilibrado"]').click();await page.wait_for_timeout(165)
        await step('Ficha comparativa de estrategia', 'Equilibrado' in await page.locator('#drawerHead').inner_text())
        await page.locator('[data-action="createPlan"]').click()
        await step('Plan genera borradores', await page.locator('#ordersCount').inner_text()=='3')
        await page.locator('[data-action="cancelOrder"]').click()
        await step('Modal cancelación', 'Cancelar' in await page.locator('#orderModalTitle').inner_text())
        await page.locator('#submitOrder').click()
        await step('Cancelar borrador', 'Cancelado' in await page.locator('#drawerHead').inner_text())
        await b.close()
    (root/'INFORME_PRUEBAS_FUNCIONALES.json').write_text(json.dumps({'checks':log,'errors':errors},ensure_ascii=False,indent=2),encoding='utf8')
    print('\n'.join(log));print('JS ERRORS',errors)
asyncio.run(main())